use crate::{Entry, Kind, Router};
use std::{
    any::TypeId,
    collections::{BTreeMap, HashSet},
    fmt::Write,
    fs, io,
    path::Path,
};
use ts_rs::{Config, TS, TypeVisitor};

pub(crate) struct Models {
    config: Config,
    visited: HashSet<TypeId>,
    declarations: BTreeMap<String, String>,
    conflict: Option<String>,
}

impl TypeVisitor for Models {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        if !self.visited.insert(TypeId::of::<T>()) {
            return;
        }
        if T::output_path().is_some() {
            let name = T::ident(&self.config);
            let declaration = T::decl(&self.config);
            if let Some(previous) = self.declarations.get(&name) {
                if previous != &declaration {
                    self.conflict = Some(name);
                }
            } else {
                self.declarations.insert(name, declaration);
            }
        }
        T::visit_generics(self);
        T::visit_dependencies(self);
    }
}

pub(crate) fn signature<I: TS + 'static, O: TS + 'static>(models: &mut Models) -> (String, String) {
    models.visit::<I>();
    models.visit::<O>();
    let input = if TypeId::of::<I>() == TypeId::of::<()>() {
        "void".to_owned()
    } else {
        I::name(&models.config)
    };
    (input, O::name(&models.config))
}

fn record(router: &Router, models: &mut Models, depth: usize, output: &mut String) {
    output.push_str("{\n");
    let indent = "  ".repeat(depth + 1);
    for (key, entry) in &router.entries {
        write!(output, "{indent}\"{key}\": ").unwrap();
        match entry {
            Entry::Router(inner) => record(inner, models, depth + 1, output),
            Entry::Procedure(procedure) => {
                let (input, result) = (procedure.signature)(models);
                let kind = match procedure.kind {
                    Kind::Query => "TRPCQueryProcedure",
                    Kind::Mutation => "TRPCMutationProcedure",
                };
                write!(
                    output,
                    "$trpc.{kind}<{{ input: {input}; output: {result}; meta: object; }}>"
                )
                .unwrap();
            }
        }
        output.push_str(";\n");
    }
    write!(output, "{}}}", "  ".repeat(depth)).unwrap();
}

pub(crate) fn export(router: &Router, path: &Path) -> io::Result<()> {
    let mut models = Models {
        config: Config::new().with_large_int("number"),
        visited: HashSet::new(),
        declarations: BTreeMap::new(),
        conflict: None,
    };
    let mut routes = String::new();
    record(router, &mut models, 1, &mut routes);
    if let Some(name) = models.conflict {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            format!("conflicting TypeScript declarations for {name}"),
        ));
    }

    let mut output = String::from(
        "// Generated by trpc-axum.\nimport type * as $trpc from '@trpc/server';\n\ndeclare namespace $rpc {\n",
    );
    for declaration in models.declarations.values() {
        writeln!(output, "  {declaration}").unwrap();
    }
    writeln!(output, "  export type $Procedures = {routes};\n}}\n").unwrap();
    output.push_str("export type AppRouter = $trpc.TRPCBuiltRouter<{\n  ctx: object;\n  meta: object;\n  errorShape: $trpc.TRPCDefaultErrorShape;\n  transformer: false;\n}, $rpc.$Procedures>;\n");
    if let Some(parent) = path.parent().filter(|p| !p.as_os_str().is_empty()) {
        fs::create_dir_all(parent)?;
    }
    fs::write(path, output)
}
